// ============================================================
// תיקון שם-קובץ שהתעקם ב-multer (העלאת מסמך)
// ------------------------------------------------------------
// הבאג: דפדפנים שולחים את שם הקובץ בקידוד UTF-8 בכותרת
// multipart/form-data, אבל גרסאות מסוימות של busboy/multer מפענחות
// את הכותרת כ-latin1 בכל מקרה. התוצאה: req.file.originalname מכיל
// מחרוזת "מעוקמת" (mojibake) שבה כל בית UTF-8 מקורי הופך לתו-latin1
// נפרד (למשל "בדיקה-עברית.pdf" מגיע כ-"ª ×�×�...pdf").
//
// התיקון: קידוד המחרוזת המעוקמת בחזרה ל-latin1 משחזר את רצף
// הבתים המקורי (קידוד latin1 הוא חד-חד-ערכי לכל תו 0-255), ואז
// פענוח כ-utf8 מחזיר את השם התקין. אם השם המקורי כבר היה תקין
// (UTF-8 תקין כבר הגיע כמחרוזת JS נכונה), הניסיון "לתקן" אותו
// שוב בדרך כלל יוצר תו-שגיאה (�, "�") — במקרה הזה משאירים
// את השם המקורי כמו שהוא, בלי לקלקל אותו.
//
// הוצא למודול נפרד (ולא הוגדר inline בתוך server.js) כדי שיהיה
// ניתן לבדיקה טהורה (unit test) ב-qa-check.mjs בלי להריץ שרת.
// ============================================================
export function fixFilenameEncoding(name) {
  if (typeof name !== 'string' || !name) return name;
  try {
    const fixed = Buffer.from(name, 'latin1').toString('utf8');
    // אם אחרי ההמרה יש תו-שגיאה (replacement character), השם המקורי
    // כבר היה תקין — השאר אותו כמו שהוא.
    if (fixed.includes('�')) return name;
    return fixed;
  } catch {
    return name;
  }
}
