// המודול הזה הוא מה שנשאר מ-`cli-auth.js` אחרי שפיצ'ר "חידוש אימות
// דרך האפליקציה" (משימה AA) הוסר לבקשת תמר. מה שהוסר ולמה:
//   • `/api/cli-auth/start|complete|status` + `CliAuthBanner` —
//     הבאנר חישב `daysLeft` מ-`token.json` שלא קיים בייצור (הטוקן בא
//     מ-.env ואין לו תאריך-תפוגה ידוע), ולכן הציג "האימות פג" כל כמה
//     דקות **אף שהניתוח עבד**. זה היה הבאג.
//   • spawn של `claude setup-token` תחת pseudo-TTY והסשן-בזיכרון —
//     `clearSession` לא הרג את תהליך-הילד, ולכן "תהליך חידוש אימות
//     כבר פתוח" נתקע עד restart.
//
// מקור הטוקן היום הוא `.env` **בלבד** (`CLAUDE_CODE_OAUTH_TOKEN`,
// root:root 644). חידוש הוא נוהל ידני — ר' RENEW-AUTH.md.
// סיווג `AUTH_EXPIRED` בניתוח נשאר (ר' document-analysis.js): הוא מה
// שמאפשר להציג "יש לפנות למפתחת" במקום "נסו שוב מאוחר יותר".
// ============================================================

/**
 * מסתיר כל סוד אפשרי מכל מחרוזת שיוצאת ללוג/לתשובה. נשאר מ-AA כי
 * פלט ה-CLI יכול להכיל טוקן, והוא מגיע לתוך הודעות-שגיאה שנרשמות.
 */
export function redactSecrets(text) {
  return String(text ?? '')
    .replace(/sk-ant-[A-Za-z0-9_-]+/g, 'sk-ant-***')
    .replace(/\b[A-Za-z0-9_#-]{20,200}#[A-Za-z0-9_-]{6,}/g, '***')
    .replace(/(code=)[^&\s"']+/gi, '$1***');
}

/**
 * מדווח מאיפה הטוקן נטען. אין כאן טעינה בפועל — `.env` נטען ע"י
 * dotenv לפני עליית השרת — רק דיווח ללוג העלייה, כדי ש-RENEW-AUTH.md
 * יוכל להפנות ל-`grep "מקור הטוקן"`. לא זורק לעולם.
 */
export function tokenSource() {
  return { source: process.env.CLAUDE_CODE_OAUTH_TOKEN ? 'env' : 'none' };
}
