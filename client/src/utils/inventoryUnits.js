export const UNIT_OPTIONS = ['יחידות', 'ליטר', 'מ"ר', "מ'", 'ק"ג', 'גליל', 'קרטון'];

/** יחידת-המידה של פריט לתצוגה — "יחידות" כברירת-מחדל בקריאה בלבד */
export function itemUnit(item) {
  return String(item?.['יחידת מידה'] || '').trim() || 'יחידות';
}

/** "52 ליטר" — כמות כבר-מעוצבת + יחידת-הפריט */
export function withUnit(formattedQuantity, item) {
  return `${formattedQuantity} ${itemUnit(item)}`;
}
