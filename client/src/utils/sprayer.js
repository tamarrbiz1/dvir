// אינו רשומה מקושרת אלא שלושה שדות על רשומת הטיפול עצמה בטבלת `ריסוסים`:
//   `סוג מרסס`          — טקסט חופשי (שם המכשיר)
//   `גודל מרסס בליטר`   — singleSelect (200 / 500 / 1000 / 1500)
//   `מספר המרססים`      — number (ריק בכל הרשומות הקיימות כרגע)
// סה"כ ליטר המים הוא **חישוב** שלנו (גודל × מספר) ולא שדה — אין שדה כזה
// ב-Airtable, ולכן כשאחד הנתונים חסר לא ממציאים מספר אלא מחזירים null
// (והתצוגה כותבת "לא צוין").
