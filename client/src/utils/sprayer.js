/** המספר שבתוך ערך ה-select ("200", ולעתיד גם "200 ליטר") */
function toNumber(v) {
  if (v == null || v === '') return null;
  const n = Number(String(v).replace(/[^\d.]/g, ''));
  return Number.isFinite(n) && n > 0 ? n : null;
}

/**
 * כל מה שצריך להציג על המרסס של טיפול אחד, מרשומת `ריסוסים` גולמית.
 * `any` = יש בכלל נתון אחד — מה שקובע אם מציגים תג בלוח/ברשימה.
 */
export function sprayerInfo(raw) {
  const name = String(raw?.['סוג מרסס'] ?? '').trim();
  const size = toNumber(raw?.['גודל מרסס בליטר']);
  const count = toNumber(raw?.['מספר המרססים']);
  return {
    name,
    size,
    count,
    // סה"כ ליטר מים = גודל מיכל × מספר מרססים. חסר אחד מהם → אין סה"כ.
    water: size && count ? size * count : null,
    any: !!(name || size || count),
  };
}
