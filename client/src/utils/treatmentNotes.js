// ============================================================
// "הערות" של טיפול — מה מוצג ומה נשאר רק בנתונים (AS-5, 14.10.2026)
// ------------------------------------------------------------
// תמר: בכרטיס הטיפול הופיע בסוף הפירוט בלוק כזה (בטיפול שיובא מדוח):
//     [מדוח ריסוסים #255] שורה 4
//     סוג טיפול: ריסוס
//     מיקום: ...
//     גידול/זן: ...
//     מינון מהדוח: 40
//     תאריך סיום: 23/07/2026
// הוא חוזר על מה שהכרטיס מציג ממילא בשורות שלו, ולכן **מוסתר**.
//
// 🔒 **סינון תצוגה בלבד — אסור לשנות את מה שנכתב ל"הערות" ב-Airtable.**
// שלוש מערכות תלויות בשורות האלה בנתונים עצמם, ומחיקתן תשבור אותן:
//   1. **אידמפוטנטיות הייבוא** — `importedLinesOf` ב-
//      server/src/spray-report-import.js קורא `MARKER_RE` מתוך ההערות
//      כדי לדעת אילו שורות של הדוח כבר יובאו. בלי הסמן, ייבוא חוזר של
//      אותו דוח ייצור כפילויות.
//   2. **ספירת "יובאו" ומחיקת דוח** — `sprayReportsHistory` ו-
//      `deleteSprayReport` מאתרים את הטיפולים של דוח בנוסחת
//      `FIND('[מדוח ריסוסים #N]', {הערות})` בצד Airtable.
//   3. **טווח התאריכים של הטיפול** — `treatmentRange` ב-
//      TreatmentsPage.jsx קורא את **סוף** הטווח משורת `תאריך סיום:`
//      (השדה `תאריך` ב-Airtable הוא תאריך בודד). בלעדיה כל הטיפולים
//      המיובאים הרב-יומיים יתכווצו ליום אחד.
// וגם תג המקור "מדוח" (`treatmentSource`) נגזר מהסמן.
//
// לכן: הפונקציות כאן **קוראות** ומפרידות, ואף אחת מהן אינה כותבת.
// בטופס העריכה מוצגות ההערות החופשיות בלבד, ו-`composeNotes` מחזירה את
// שורות-הייבוא בשמירה — אותה תבנית שכבר הייתה ל"תאריך סיום" לבדו.
//
// JS טהור (לא jsx) כדי שסוויטת הבדיקות תייבא אותו ישירות.
// ============================================================

/** שורת הסמן שכותב ייבוא הדוחות. זהה ל-MARKER_RE ב-spray-report-import.js */
const MARKER_LINE_RE = /^\s*\[מדוח(?: ריסוסים)? ?#?(\d*)\](?:\s*שורה\s*(\d+))?\s*$/;

/**
 * תחיליות השורות שהייבוא מוסיף להערות (ר' buildRow ב-
 * spray-report-import.js) — כולן חוזרות על מה שהכרטיס מציג בשורות שלו.
 * `תאריך סיום:` כאן גם הוא: הכרטיס מציג את הטווח, והטופס מנהל אותו
 * בשדות "מתאריך"/"עד תאריך".
 */
const IMPORT_PREFIXES = ['סוג טיפול:', 'מיקום:', 'גידול/זן:', 'מינון מהדוח:', 'מספר ריסוס:', 'תאריך סיום:', 'מבנה לא זוהה:'];

const isImportLine = (line) => MARKER_LINE_RE.test(line)
  || IMPORT_PREFIXES.some((p) => line.trimStart().startsWith(p));

const linesOf = (notes) => String(notes ?? '').split('\n');

/** ההערות שמוצגות למשתמשת: הטקסט החופשי בלבד ('' אם אין) */
export function visibleNotes(notes) {
  return linesOf(notes).filter((l) => !isImportLine(l)).join('\n').trim();
}

/** השורות שהוסתרו — מה שצריך להחזיר בשמירה כדי לא לאבד אותן */
export function importNoteLines(notes) {
  return linesOf(notes).filter((l) => isImportLine(l) && l.trim()).map((l) => l.trim());
}

// ============================================================
// AS-7 (14.10.2026) — הגידול והזן **מהדוח**, לא מהתוכנית
// ------------------------------------------------------------
// תמר: בטיפול מיובא הגידול והזן הם מה שכתוב בדוח, וזה **הקובע** — גם
// אם מקושרת תוכנית שתילה של גידול אחר. רק כשאין שורה כזו (טיפול ידני)
// נגזרים הגידול והזן מהתוכנית, כמו עד היום.
//
// זה מתיישב עם הסתרת ההערות: השורה **נשארת** ב-Airtable ונקראת מכאן —
// היא פשוט לא מוצגת כטקסט. שתי הפונקציות קוראות את ההערות הגולמיות.
//
// הפורמט שהייבוא כותב (buildRow ב-spray-report-import.js):
//   notes.push(`גידול/זן: ${[crop, variety].filter(Boolean).join(' · ')}`)
// ולכן שלושה מקרים:
//   • שניהם     → "גידול/זן: מלפפון · היילוקס"
//   • רק גידול  → "גידול/זן: מלפפון"  (בלי מפריד, הזן ריק)
//   • אף אחד    → השורה **לא נכתבת** → null, ואז נפילה-לאחור לתוכנית
// המפריד הוא '·' (middle dot); לא מסתמכים על הרווחים שסביבו.
// ============================================================
const CROP_LINE_RE = /^\s*גידול\/זן:\s*(.*)$/;

/**
 * הגידול והזן כפי שהם בדוח, מתוך שורת ההערות.
 * @returns {{crop: string, variety: string}|null} null = אין שורה כזו (או שהיא ריקה)
 */
export function cropFromNotes(notes) {
  for (const line of linesOf(notes)) {
    const m = CROP_LINE_RE.exec(line);
    if (!m) continue;
    const parts = m[1].split('·').map((s) => s.trim()).filter(Boolean);
    if (!parts.length) return null; // "גידול/זן:" בלי תוכן — כאילו אין שורה
    // יותר משני חלקים (לא קורה בייבוא, אבל לא מתפוצצים): הראשון גידול, השאר זן
    return { crop: parts[0], variety: parts.slice(1).join(' · ') };
  }
  return null;
}

/** מספר הדוח שממנו יובא הטיפול, מתוך הסמן. null בטיפול ידני. */
export function reportNumberFromNotes(notes) {
  for (const line of linesOf(notes)) {
    const m = MARKER_LINE_RE.exec(line);
    if (m && m[1]) return m[1];
  }
  return null;
}

/**
 * ההערות לכתיבה חזרה ל-Airtable: שורות-הייבוא שהוסתרו **חוזרות**, ואחריהן
 * הטקסט החופשי שהמשתמשת הקלידה. `endDateLine` (למשל "תאריך סיום: 23/07/2026")
 * נוסף בסוף ומחליף כל שורת-סיום שהייתה — הטופס הוא מקור האמת לטווח.
 *
 * ⚠️ זו הנקודה המסוכנה של AS-5: באג כאן משתיק את האידמפוטנטיות של
 * הייבוא ואת מחיקת-הדוח. לכן היא פונקציה טהורה ונבדקת.
 */
export function composeNotes({ hiddenLines = [], freeText = '', endDateLine = '' } = {}) {
  const kept = hiddenLines.filter((l) => l && !l.trimStart().startsWith('תאריך סיום:'));
  const free = String(freeText || '').replace(/\n?תאריך סיום:.*$/m, '').trim();
  return [...kept, free, String(endDateLine || '').trim()].filter(Boolean).join('\n');
}
