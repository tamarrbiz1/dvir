// שם חודש מקוצר לפי השפה הפעילה (לצירי גרפים ולפילטרים)
export function monthShort(i) {
  try {
    return new Date(2000, i, 1).toLocaleDateString(currentLang === 'th' ? 'th-TH' : 'he-IL', { month: 'short' });
  } catch {
    return String(i + 1);
  }
}
